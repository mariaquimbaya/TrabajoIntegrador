def describir(df, cols):
    filas = {}
    for c, nombre in cols.items():
        x = df[c].dropna()
        if len(x) == 0:
            continue
        moda = x.round(0).mode()
        filas[nombre] = {
            # Tendencia central
            "n": len(x),
            "Media": x.mean(),
            "Mediana": x.median(),
            "Moda (redondeada)": moda.iloc[0] if len(moda) else np.nan,
            # Dispersión
            "Desv. estándar": x.std(),
            "Varianza": x.var(),
            "Coef. de variación (%)": x.std() / x.mean() * 100 if x.mean() != 0 else np.nan,
            "Mínimo": x.min(),
            "Máximo": x.max(),
            "Rango": x.max() - x.min(),
            # Posición
            "P5": x.quantile(.05),
            "Q1 (P25)": x.quantile(.25),
            "Q3 (P75)": x.quantile(.75),
            "P95": x.quantile(.95),
            "Rango intercuartílico (IQR)": x.quantile(.75) - x.quantile(.25),
            # Forma
            "Asimetría": stats.skew(x, bias=False),
            "Curtosis (exceso)": stats.kurtosis(x, bias=False),
            "Error estándar de la media": x.sem(),
        }
    return pd.DataFrame(filas).T

