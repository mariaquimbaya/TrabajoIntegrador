def describir_variables(df, cols):
    filas = {}
    for columna, nombre in cols.items():
        x_ = df[columna].dropna()
        if x_.empty:
            continue
        moda = x_.round(0).mode()
        filas[nombre] = {
            "n": len(x_),
            "Media": x_.mean(),
            "Mediana": x_.median(),
            "Moda (redondeada)": moda.iloc[0] if len(moda) else np.nan,
            "Desv. estándar": x_.std(),
            "Varianza": x_.var(),
            "Coef. de variación (%)": x_.std() / x_.mean() * 100 if x_.mean() != 0 else np.nan,
            "Mínimo": x_.min(),
            "Máximo": x_.max(),
            "Rango": x_.max() - x_.min(),
            "P5": x_.quantile(.05),
            "Q1 (P25)": x_.quantile(.25),
            "Q3 (P75)": x_.quantile(.75),
            "P95": x_.quantile(.95),
            "Rango intercuartílico (IQR)": x_.quantile(.75) - x_.quantile(.25),
            "Asimetría": stats.skew(x_, bias=False),
            "Curtosis (exceso)": stats.kurtosis(x_, bias=False),
            "Error estándar de la media": x_.sem(),
        }
    return pd.DataFrame(filas).T


