def calcular_indice(df):
    """Índice = TPD del mes / promedio del TPD mensual de su año. Solo años con 12 meses."""
    d = df[["tpd"]].dropna().copy()
    d["anio"], d["mes"] = d.index.year, d.index.month
    d = d[d.groupby("anio")["tpd"].transform("count") == 12]
    d["indice"] = d["tpd"] / d.groupby("anio")["tpd"].transform("mean")
    tabla = d.groupby("mes")["indice"].agg(**{"Índice estacional": "mean", "Desv. estándar": "std"})
    matriz = d.pivot_table(index="anio", columns="mes", values="indice")
    return tabla, matriz, sorted(d["anio"].unique())


