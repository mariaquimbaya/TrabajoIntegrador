    j = xa.join(xb, lsuffix="_a", rsuffix="_b", how="inner")
    dif = (j["ape_a"] - j["ape_b"]) * 100
    return pd.Series({"n_pares": len(j), "dif_MAPE_pp": dif.mean(), "% pares donde mejora": (dif < 0).mean() * 100})
