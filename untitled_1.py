def indice_base_100(serie):
    """
    Convierte una serie a índice Base 100 utilizando
    enero de 2018 como periodo de referencia.
    """

    serie = pd.to_numeric(serie, errors="coerce")

    fecha_base = pd.Timestamp("2018-01-31")

    if fecha_base not in serie.index:
        raise ValueError(
            f"No se encontró enero de 2018 para {serie.name}. "
            "Revise el índice de fechas."
        )

    base_enero_2018 = serie.loc[fecha_base]

    if pd.isna(base_enero_2018) or base_enero_2018 == 0:
        raise ValueError(
            f"El valor de enero de 2018 para {serie.name} "
            "es nulo o igual a cero."
        )

    return serie / base_enero_2018 * 100


