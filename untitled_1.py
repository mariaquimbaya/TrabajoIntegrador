def calendario(indice):
    """Variables de calendario por mes. 'indice' contiene fechas a fin de mes."""
    anios = range(indice.year.min(), indice.year.max() + 2)
    co = holidays.CO(years=anios)
    filas = []
    for d_ in indice:
        fin = pd.Timestamp(d_).normalize() + pd.offsets.MonthEnd(0)   # asegura fin de mes
        inicio = fin.to_period("M").to_timestamp()                    # primer día del mes
        dias_ = pd.date_range(inicio, fin, freq="D")
        jueves_santo = pd.Timestamp(easter(fin.year)) - pd.Timedelta(days=3)
        filas.append(dict(
            dias=len(dias_),
            n_festivos=sum(x.date() in co for x in dias_),
            n_findes=int((dias_.dayofweek >= 5).sum()),
            semana_santa=int(jueves_santo.year == fin.year and jueves_santo.month == fin.month),
        ))
    return pd.DataFrame(filas, index=indice)


