# FUNCIÓN PARA CALCULAR R²
# ============================================================

def calcular_r2(serie_x, serie_y):

    datos_validos = pd.concat(
        [serie_x, serie_y],
        axis=1
    ).dropna()

    if len(datos_validos) < 3:
        return np.nan

    correlacion = datos_validos.iloc[:, 0].corr(
        datos_validos.iloc[:, 1]
    )

    return correlacion ** 2


